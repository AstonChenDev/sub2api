-- Dedicated Hugging Face pool metadata. Credentials intentionally remain in
-- accounts so existing concurrency, usage-log and billing foreign keys keep
-- working, but HF accounts are not linked through account_groups and therefore
-- never enter the legacy scheduler snapshot.

CREATE TABLE IF NOT EXISTS hf_pools (
    id BIGSERIAL PRIMARY KEY,
    group_id BIGINT NOT NULL REFERENCES groups(id) ON DELETE RESTRICT,
    name VARCHAR(100) NOT NULL,
    base_url TEXT NOT NULL DEFAULT 'https://router.huggingface.co',
    priority INTEGER NOT NULL DEFAULT 50 CHECK (priority BETWEEN 0 AND 1000000),
    weight INTEGER NOT NULL DEFAULT 100 CHECK (weight BETWEEN 1 AND 1000000),
    status VARCHAR(20) NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'disabled')),
    models JSONB NOT NULL DEFAULT '["*"]'::jsonb,
    failure_threshold INTEGER NOT NULL DEFAULT 5 CHECK (failure_threshold BETWEEN 1 AND 1000),
    circuit_cooldown_seconds INTEGER NOT NULL DEFAULT 30 CHECK (circuit_cooldown_seconds BETWEEN 1 AND 86400),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    deleted_at TIMESTAMPTZ NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS hf_pools_group_name_active_uidx
    ON hf_pools (group_id, LOWER(name)) WHERE deleted_at IS NULL;
CREATE INDEX IF NOT EXISTS hf_pools_group_schedule_idx
    ON hf_pools (group_id, priority, id) WHERE deleted_at IS NULL AND status = 'active';

-- A token fingerprint is a keyed HMAC generated by the application. The
-- partial unique index deduplicates both existing rows and one bulk import
-- without exposing token plaintext.
CREATE UNIQUE INDEX IF NOT EXISTS accounts_hf_token_fingerprint_active_uidx
    ON accounts ((extra ->> 'hf_token_fingerprint'))
    WHERE deleted_at IS NULL
      AND platform = 'huggingface'
      AND (extra ->> 'hf_token_fingerprint') IS NOT NULL;

CREATE INDEX IF NOT EXISTS accounts_hf_pool_schedule_idx
    ON accounts ((extra ->> 'hf_pool_id'), priority, id)
    WHERE deleted_at IS NULL AND platform = 'huggingface';

CREATE INDEX IF NOT EXISTS accounts_hf_recovery_idx
    ON accounts ((extra ->> 'hf_recover_at'), id)
    WHERE deleted_at IS NULL
      AND platform = 'huggingface'
      AND status = 'disabled'
      AND (extra ->> 'hf_recover_at') IS NOT NULL;

