-- HF credentials are scheduled only through hf_pools. A database guard keeps
-- future generic/bulk code paths from accidentally inserting them into the
-- legacy account_groups snapshot.
CREATE OR REPLACE FUNCTION reject_hf_account_group_binding()
RETURNS TRIGGER AS $$
BEGIN
    IF EXISTS (SELECT 1 FROM accounts WHERE id = NEW.account_id AND platform = 'huggingface') THEN
        RAISE EXCEPTION 'Hugging Face accounts must not be bound through account_groups'
            USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_reject_hf_account_group_binding ON account_groups;
CREATE TRIGGER trg_reject_hf_account_group_binding
    BEFORE INSERT OR UPDATE OF account_id ON account_groups
    FOR EACH ROW EXECUTE FUNCTION reject_hf_account_group_binding();

-- Keep pool ownership and group lifecycle valid even if a future code path
-- bypasses the dedicated service.
CREATE OR REPLACE FUNCTION validate_hf_pool_group()
RETURNS TRIGGER AS $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM groups
        WHERE id = NEW.group_id AND platform = 'huggingface' AND deleted_at IS NULL
    ) THEN
        RAISE EXCEPTION 'Hugging Face pools require an active Hugging Face group record'
            USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_validate_hf_pool_group ON hf_pools;
CREATE TRIGGER trg_validate_hf_pool_group
    BEFORE INSERT OR UPDATE OF group_id ON hf_pools
    FOR EACH ROW EXECUTE FUNCTION validate_hf_pool_group();

CREATE OR REPLACE FUNCTION protect_hf_pool_group_lifecycle()
RETURNS TRIGGER AS $$
BEGIN
    IF EXISTS (SELECT 1 FROM hf_pools WHERE group_id = OLD.id AND deleted_at IS NULL)
       AND (NEW.platform IS DISTINCT FROM OLD.platform
            OR (OLD.deleted_at IS NULL AND NEW.deleted_at IS NOT NULL)) THEN
        RAISE EXCEPTION 'Delete Hugging Face pools before changing or deleting their group'
            USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_protect_hf_pool_group_lifecycle ON groups;
CREATE TRIGGER trg_protect_hf_pool_group_lifecycle
    BEFORE UPDATE OF platform, deleted_at ON groups
    FOR EACH ROW EXECUTE FUNCTION protect_hf_pool_group_lifecycle();
